def _seed_demo_traffic(db: Session) -> None:
    from app.services.orchestrator import run_security_pipeline
    logger.info("generating demo traffic through the real pipeline...")
    for session_id, prompt in DEMO_TRAFFIC:
        try:
            run_security_pipeline(db, session_id, prompt, user_id=None,
                                  emit=lambda name, data: None)
        except Exception as exc:  # noqa: BLE001 - seeding must not break startup
            logger.warning("demo traffic seeding failed for %r: %s", prompt[:40], exc)
            db.rollback()
    logger.info("demo traffic seeded")
