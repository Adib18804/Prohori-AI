def init_database() -> None:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        seed_demo_users(db)
        added = attack_memory.seed_attack_patterns(db)
        logger.info("database ready (seeded %s new attack patterns)", added)

        from app.models import ProtectedRequest
        if db.query(ProtectedRequest).count() == 0:
            _seed_demo_traffic(db)
        
        # Seed extended plans
        _seed_extended_plans(db)
    finally:
        db.close()
    ml_classifier.train_async()


